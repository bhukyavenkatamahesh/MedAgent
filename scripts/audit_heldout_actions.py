"""Episode-level AND action-instance-level breakdown of a re-scored held-out run.

Reads the episodes.jsonl files written by scripts/summarize_heldout.py and emits markdown.
`heldout_v1.json`'s `order_required` field is used ONLY for the independent stratified check at
the end; it is never an evaluator input.

    python scripts/audit_heldout_actions.py --scored outputs/heldout_v1_audit \
        --spec medagentbench_setup/heldout_v1.json --mab ../../MedAgentBench/MedAgentBench \
        --out runs/2026-11-16_slm-heldout_n20/action_audit_summary.md
"""
import argparse
import collections
import json
from pathlib import Path

PROMPT = {"fewshot2": "v2 sequence", "fewshot3": "v3 format-only", "fewshot4": "v4 decision"}
TOOLS = ["medicationrequest.create", "servicerequest.create"]


def rows(scored: Path):
    out = []
    for f in sorted(scored.glob("*/*_task*/episodes.jsonl")):
        prompt, leaf = f.parts[-3], f.parts[-2]
        agent, task = leaf.rsplit("_", 1)
        model, _, rep = agent.partition("-ctx8k")
        eps = [json.loads(l) for l in f.read_text().splitlines()]
        out.append({"prompt": prompt, "model": model, "repeat": rep.lstrip("-") or "t0 (temp 0)",
                    "task": task, "eps": eps})
    return out


def counts(eps):
    req = [e for e in eps if e["action_requirement_status"] == "REQUIRED"]
    att = lambda e: set(e["attempted_actions"]) & set(e["required_actions"])
    c = {
        "n": len(eps),
        "pass": sum(e["terminal_result"] == "PASS" for e in eps),
        "fail": sum(e["terminal_result"] == "FAIL" for e in eps),
        "verified": sum(e["verified_outcome"] == "VERIFIED_PASS" for e in eps),
        "required": len(req),
        "req_all_attempted": sum(bool(e["required_actions"]) and set(e["required_actions"]) <= att(e) for e in req),
        "req_partial": sum(bool(att(e)) and not set(e["required_actions"]) <= att(e) for e in req),
        "req_none": sum(not att(e) for e in req),
        "missed_eps": sum(e["missed_required_action"] for e in eps),
        "not_required": sum(e["action_requirement_status"] == "NOT_REQUIRED" for e in eps),
        "unnecessary_eps": sum(e["unnecessary_action"] for e in eps),
        "undetermined": sum(e["action_requirement_status"] == "UNDETERMINED" for e in eps),
        "no_finish": sum(not e["complete_trace"] for e in eps),
        "req_no_finish": sum(not e["complete_trace"] for e in req),
    }
    for t in TOOLS:
        c[f"req_{t}"] = sum(t in e["required_actions"] for e in eps)
        c[f"att_{t}"] = sum(t in e["required_actions"] and t in e["attempted_actions"] for e in eps)
        c[f"missed_{t}"] = sum(t in e["missed_required_actions"] for e in eps)
        c[f"unnec_{t}"] = sum(t in e["unnecessary_actions"] for e in eps)
    return c


def table(header, lines):
    return "\n".join(["| " + " | ".join(header) + " |",
                      "|" + "|".join("---" for _ in header) + "|"] + ["| " + " | ".join(l) + " |" for l in lines])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scored", required=True)
    ap.add_argument("--spec", required=True)
    ap.add_argument("--mab", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    data = rows(Path(a.scored))
    spec = json.loads(Path(a.spec).read_text())
    tasks = json.loads((Path(a.mab) / "data/medagentbench/test_data_v2.json").read_text())
    external = {tasks[c["index"]]["id"]: c["order_required"] for c in spec["cases"]}
    all_eps = [e for r in data for e in r["eps"]]
    tot = counts(all_eps)

    md = ["# Action-requirement audit of the held-out runs (re-scored 2026-11-17)",
          "",
          "Generated by `scripts/audit_heldout_actions.py` from the **saved** trajectories; no model",
          "inference was re-run. Policies: `mab_task9_potassium_v2`, `mab_task5_magnesium_v2`.",
          "The original run tables in this folder's README are unchanged.",
          "",
          "## 1. Totals", "",
          f"- Episodes: **{tot['n']}** ({len(data)} condition/task groups; 24 runs x 20 cases)",
          f"- Terminal: {tot['pass']} PASS, {tot['fail']} FAIL; VERIFIED_PASS: {tot['verified']}",
          f"- Action requirement: **REQUIRED {tot['required']}**, NOT_REQUIRED {tot['not_required']}, "
          f"UNDETERMINED {tot['undetermined']}",
          f"- Episodes without a final FINISH: {tot['no_finish']}",
          "",
          "### What the \"zero completed attempts\" statement means", "",
          "Among the **REQUIRED** episodes:", "",
          table(["Attempt completeness", "Episodes"],
                [["Every required action attempted", f"**{tot['req_all_attempted']}**"],
                 ["Some but not all attempted (partial)", f"**{tot['req_partial']}**"],
                 ["None attempted", f"**{tot['req_none']}**"],
                 ["&nbsp;&nbsp;of those, flagged MISSED_REQUIRED_ACTION (trace ends in FINISH)", f"{tot['missed_eps']}"],
                 ["&nbsp;&nbsp;of those, no final FINISH, so no missed-action claim",
                  f"{tot['req_none'] - tot['missed_eps']}"],
                 ["(REQUIRED episodes without a final FINISH, including the partial one)",
                  f"{tot['req_no_finish']}"]]),
          "",
          "## 2. Action-instance level (each required tool counted separately)", "",
          table(["Required tool", "Required instances (denominator)", "Attempted", "Missed (numerator)",
                 "Unnecessary attempts"],
                [[f"`{t}`", str(tot[f"req_{t}"]), str(tot[f"att_{t}"]), f"**{tot[f'missed_{t}']}**",
                  str(tot[f"unnec_{t}"])] for t in TOOLS]),
          "",
          "Task 9 configures both tools; task 5 configures only `medicationrequest.create`, so the",
          "`servicerequest.create` denominator comes from task 9 alone. Per task:", "",
          ]
    per_task = {}
    for t in ("task9", "task5"):
        eps = [e for r in data if r["task"] == t for e in r["eps"]]
        per_task[t] = counts(eps)
    md += [table(["Task", "Required tool", "Required instances", "Attempted", "Missed"],
                 [[t, f"`{tool}`", str(per_task[t][f"req_{tool}"]), str(per_task[t][f"att_{tool}"]),
                   str(per_task[t][f"missed_{tool}"])]
                  for t in ("task9", "task5") for tool in TOOLS if per_task[t][f"req_{tool}"] or tool == TOOLS[0]]),
           "",
           "## 3. By model, prompt, seed and task", "",
           table(["Model", "Prompt", "Seed", "Task", "n", "PASS", "VERIF", "REQ", "all att.", "partial",
                  "none att.", "missed eps", "NOT_REQ", "unnec eps", "UNDET", "no FINISH"],
                 [[r["model"], PROMPT.get(r["prompt"], r["prompt"]), r["repeat"], r["task"],
                   str(c["n"]), str(c["pass"]), str(c["verified"]), str(c["required"]),
                   str(c["req_all_attempted"]), str(c["req_partial"]), str(c["req_none"]),
                   str(c["missed_eps"]), str(c["not_required"]), str(c["unnecessary_eps"]),
                   str(c["undetermined"]), str(c["no_finish"])]
                  for r in sorted(data, key=lambda r: (r["model"], r["prompt"], r["repeat"], r["task"]))
                  for c in [counts(r["eps"])]]),
           "",
           "## 4. Independent check against the case manifest", "",
           "`heldout_v1.json`'s `order_required` flag is **not** an evaluator input. Comparing it with the",
           "evaluator's episode status is therefore an independent consistency check:", ""]
    cross = collections.Counter((external[e["task_id"]], e["action_requirement_status"]) for e in all_eps)
    md += [table(["Manifest says an order is required", "Evaluator status", "Episodes"],
                 [[str(k[0]), k[1], str(v)] for k, v in sorted(cross.items(), key=lambda kv: (str(kv[0][0]), kv[0][1]))]),
           "",
           "`REQUIRED` must never appear against a manifest `False`, and `NOT_REQUIRED` never against a",
           "manifest `True`; `UNDETERMINED` may appear against either, because the agent did not retrieve",
           "the evidence. Any violation of the first two is an evaluator bug.", ""]
    Path(a.out).write_text("\n".join(md) + "\n")
    print("\n".join(md[:40]))
    bad = {k: v for k, v in cross.items() if (k[0] and k[1] == "NOT_REQUIRED") or (not k[0] and k[1] == "REQUIRED")}
    print("\nMANIFEST VIOLATIONS:", bad or "none")


if __name__ == "__main__":
    main()
